"""Synthetic schedules test relayed boundary claims, never certify an Exness feed.

FULL_TRADING outside the reported close-only interval is a conditional fixture
assumption. No runnable broker calendar or approval is generated by these tests.
"""
from copy import deepcopy
from datetime import datetime, timedelta, timezone
from hashlib import sha256
import json
from pathlib import Path
import unittest

from iat.session_config import compile_session_config, SessionConfigError
from iat.sessions import SessionValidationError
from test_session_v2 import synthetic_v2, window

DAYS=('2026-11-11','2026-11-12','2026-11-13')


def at(day, clock):
    return datetime.fromisoformat(day+'T'+clock+'+00:00')


def boundary_fixture(post_reopen='FULL_TRADING', trade_verified=None, friday_reopens=True):
    c=synthetic_v2()
    schedule={'quotes':[window('00:00:00','21:58:00',0),window('23:00:00','00:00:00',1)],
        'phases':[window('00:00:00','21:58:00',0,'FULL_TRADING'),
                  window('21:58:00','23:00:00',0,'CLOSED'),
                  window('23:00:00','23:02:00',0,'CLOSE_ONLY'),
                  window('23:02:00','00:00:00',1,post_reopen)]}
    c['exceptions']={day:deepcopy(schedule) for day in DAYS}
    if not friday_reopens:
        c['exceptions']['2026-11-13']={'quotes':[window('00:00:00','21:58:00',0)],
            'phases':[window('00:00:00','21:58:00',0,'FULL_TRADING'),window('21:58:00','00:00:00',1,'CLOSED')]}
    c['verification']['trade_schedule_verified']=(post_reopen!='UNKNOWN') if trade_verified is None else trade_verified
    return compile_session_config(c)


class ExnessDatedBoundaryTests(unittest.TestCase):
    def test_quote_and_trade_phase_endpoints_for_each_reported_day(self):
        cal=boundary_fixture()
        for day in DAYS:
            for clock,state,quotes,opening,closing in (
                ('21:57:59','FULL_TRADING',True,True,True),
                ('21:58:00','CLOSED',False,False,False),
                ('22:59:59','CLOSED',False,False,False),
                ('23:00:00','CLOSE_ONLY',True,False,True),
                ('23:01:59','CLOSE_ONLY',True,False,True),
                ('23:02:00','FULL_TRADING',True,True,True)):
                with self.subTest(day=day,clock=clock):
                    p=cal.permissions_at(at(day,clock))
                    self.assertEqual(p['phase'],state);self.assertIs(p['market_data_expected'],quotes)
                    self.assertIs(p['broker_open_positions'],opening);self.assertIs(p['broker_close_positions'],closing)
                    self.assertIs(p['iat_execution_allowed'],False)
    def test_unconfirmed_new_position_permission_is_not_inferred_from_quotes(self):
        cal=boundary_fixture('UNKNOWN')
        for day in DAYS:
            p=cal.permissions_at(at(day,'23:02:00'))
            self.assertTrue(p['market_data_expected']);self.assertEqual(p['phase'],'UNKNOWN')
            self.assertIsNone(p['broker_open_positions']);self.assertFalse(p['iat_execution_allowed'])
            self.assertEqual(cal.classify_bar(at(day,'23:02:00'),'M1')['classification'],'UNKNOWN_SESSION')
    def test_unknown_permission_cannot_be_marked_a_verified_trade_schedule(self):
        with self.assertRaises(SessionConfigError) as err:boundary_fixture('UNKNOWN',trade_verified=True)
        self.assertEqual(err.exception.code,'SESSION_PHASE_UNKNOWN')
    def test_m1_last_full_candle_ends_at_break_and_next_open_is_outside(self):
        cal=boundary_fixture()
        for day in DAYS:
            self.assertEqual(cal.classify_bar(at(day,'21:57:00'),'M1')['classification'],'FULL_SESSION_BAR')
            self.assertEqual(cal.classify_bar(at(day,'21:58:00'),'M1')['classification'],'OUTSIDE_SESSION')
    def test_m5_partial_close_is_180_seconds_not_a_full_five_minute_bar(self):
        cal=boundary_fixture()
        for day in DAYS:
            r=cal.classify_bar(at(day,'21:55:00'),'M5',observed_finalized=True,as_of=at(day,'23:10:00'))
            self.assertEqual(r['classification'],'PARTIAL_SESSION_CLOSE');self.assertEqual(r['market_open_seconds'],180)
            self.assertEqual(r['market_open_portions'][0]['end'],at(day,'21:58:00').isoformat())
            self.assertEqual(r['scheduled_end_utc'],at(day,'22:00:00').isoformat());self.assertFalse(r['eligible_for_strategy'])
            self.assertEqual(cal.classify_bar(at(day,'22:00:00'),'M5')['classification'],'OUTSIDE_SESSION')
    def test_close_only_m1_bars_have_quotes_but_are_not_strategy_eligible(self):
        cal=boundary_fixture()
        for day in DAYS:
            for clock in ('23:00:00','23:01:00'):
                r=cal.classify_bar(at(day,clock),'M1',observed_finalized=True,as_of=at(day,'23:10:00'))
                self.assertEqual(r['classification'],'FULL_SESSION_BAR');self.assertEqual(r['phase_states'],['CLOSE_ONLY'])
                self.assertFalse(r['broker_open_positions']);self.assertFalse(r['eligible_for_strategy'])
                self.assertFalse(r['iat_execution_allowed'])
    def test_m5_reopening_bar_has_full_quotes_but_mixed_trade_phases(self):
        cal=boundary_fixture()
        for day in DAYS:
            r=cal.classify_bar(at(day,'23:00:00'),'M5',observed_finalized=True,as_of=at(day,'23:10:00'))
            self.assertEqual(r['classification'],'FULL_SESSION_BAR');self.assertEqual(r['market_open_seconds'],300)
            self.assertEqual(r['phase_states'],['CLOSE_ONLY','FULL_TRADING'])
            self.assertFalse(r['broker_open_positions']);self.assertFalse(r['eligible_for_strategy'])
    def test_2302_is_not_an_m5_open_and_first_full_phase_m5_opens_2305(self):
        cal=boundary_fixture()
        for day in DAYS:
            with self.assertRaises(SessionValidationError) as err:cal.classify_bar(at(day,'23:02:00'),'M5')
            self.assertEqual(err.exception.code,'TIMEFRAME_MISALIGNED')
            r=cal.classify_bar(at(day,'23:05:00'),'M5',observed_finalized=True,as_of=at(day,'23:10:00'))
            self.assertTrue(r['eligible_for_strategy']);self.assertFalse(r['iat_execution_allowed'])
    def test_phase_resumption_does_not_establish_finality_or_closed_m1(self):
        cal=boundary_fixture()
        for day in DAYS:
            for options in ({},{'observed_finalized':True,'as_of':at(day,'23:02:00')}):
                r=cal.classify_bar(at(day,'23:02:00'),'M1',**options)
                self.assertFalse(r['eligible_for_strategy']);self.assertFalse(r['iat_execution_allowed'])
            r=cal.classify_bar(at(day,'23:02:00'),'M1',observed_finalized=True,as_of=at(day,'23:03:00'))
            self.assertTrue(r['eligible_for_strategy']);self.assertFalse(r['iat_execution_allowed'])
    def test_expected_ordinary_opens_exclude_partial_and_close_only_bars(self):
        cal=boundary_fixture()
        for day in DAYS:
            m5=list(cal.expected_opens(at(day,'21:50:00'),at(day,'23:11:00'),timedelta(minutes=5)))
            self.assertEqual(m5,[at(day,t) for t in ('21:50:00','23:05:00','23:10:00')])
            m1=list(cal.expected_opens(at(day,'23:00:00'),at(day,'23:04:00'),timedelta(minutes=1)))
            self.assertEqual(m1,[at(day,t) for t in ('23:02:00','23:03:00')])
    def test_ordinary_request_is_closed_then_restricted_without_enabling_execution(self):
        cal=boundary_fixture()
        for day in DAYS:
            for clock,code in [('21:58:00','SESSION_CLOSED'),('23:00:00','BROKER_PHASE_RESTRICTED')]:
                with self.assertRaises(SessionValidationError) as err:cal.validate_request('XAUUSD',at(day,clock),timedelta(minutes=1))
                self.assertEqual(err.exception.code,code)
    def test_friday_weekend_alternative_remains_closed_without_quotations(self):
        self.assertEqual(at('2026-11-13','23:00:00').weekday(),4)
        cal=boundary_fixture(friday_reopens=False)
        for clock in ('21:58:00','23:00:00','23:02:00'):
            p=cal.permissions_at(at('2026-11-13',clock))
            self.assertEqual(p['phase'],'CLOSED');self.assertFalse(p['market_data_expected'])
            self.assertFalse(p['broker_open_positions']);self.assertFalse(p['iat_execution_allowed'])
    def test_evidence_hash_and_unapproved_dated_claims_remain_intact(self):
        root=Path('docs/source_reviews/exness-2026-11-11-13');e=json.loads((root/'evidence.json').read_text(encoding='utf-8'))
        self.assertEqual(e['artifact']['sha256'],sha256((root/e['artifact']['file']).read_bytes()).hexdigest())
        self.assertEqual(e['broker_reported_claims']['chart_ohlc_basis'],'BID')
        self.assertEqual(e['independent_authentication'],'PENDING');self.assertEqual(e['historical_validation'],'PENDING')
        self.assertEqual(e['historical_comparisons'],'NOT_RUN');self.assertEqual(e['exness'],'BLOCKED')
        self.assertEqual(e['signal'],'WAIT');self.assertFalse(e['execution_allowed']);self.assertFalse(e['operational_calendar_changed'])
        self.assertIsNone(e['provider_sent_at']);self.assertEqual(e['attachment_inventory'],'NOT_SUPPLIED')
        self.assertIn('EXPLICIT_NEW_POSITION_PERMISSION_AT_OR_AFTER_23_02',e['unresolved'])
